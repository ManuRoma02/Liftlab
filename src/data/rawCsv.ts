const lines = rawCsvData.split('\n');
const exercises = [];
for (let i = 0; i < lines.length; i++) {
  const line = lines[i].trim();
  if (line === '') continue;
  
  // Extract lines that look like valid exercises
  const parts = line.split(',');
  if (parts.length >= 2) {
    const exerciseName = parts[0].trim().replace(/^"|"$/g, '');
    let catName = exerciseName;
    if (catName.startsWith("Testo: ")) catName = catName.substring(7).trim();

    // Check if line actually looks like exercise
    if (["Donna", "Uomo", "|", "Intermedio", "Novizio", "Testo:", "Bilanciere", "Manubri", "Principiante", "Avanzato", "nome", "livello", "attrezzo"].includes(catName)) {
        let e2 = parts[1].trim().replace(/^"|"$/g, '');
        if (e2.startsWith("Testo: ")) e2 = e2.substring(7).trim();
        if (!["Donna", "Uomo", "|", "Intermedio", "Novizio", "Testo:", "Bilanciere", "Manubri", "Principiante", "Avanzato", "attrezzo"].includes(e2)) {
             catName = e2;
        } else if (parts.length > 2) {
            let e3 = parts[2].trim().replace(/^"|"$/g, '');
            if (e3.startsWith("Testo: ")) e3 = e3.substring(7).trim();
            if (!["Donna", "Uomo", "|", "Intermedio", "Novizio", "Testo:", "Bilanciere", "Manubri", "Principiante", "Avanzato", "attrezzo"].includes(e3)) {
                catName = e3;
            } else continue;
        } else continue;
    }

    if (catName.length < 5) continue;
    
    // Get true equipment
    let eqStr = parts.join(',');
    let trueEq = "Bodyweight";
    if (eqStr.includes("Bilanciere") || eqStr.includes("Barbell")) trueEq = "Barbell";
    else if (eqStr.includes("Manubri") || eqStr.includes("Dumbbell")) trueEq = "Dumbbell";
    else if (eqStr.includes("Cavo") || eqStr.includes("Cavi") || eqStr.includes("Machine") || eqStr.includes("Macchina")) trueEq = "Machine";
    else if (eqStr.includes("Piatto") || eqStr.includes("Piastra")) trueEq = "Weight";
    else if (eqStr.includes("Kettlebell")) trueEq = "Kettlebell";

    exercises.push({
       id: "e_csv_" + Math.floor(Math.random()*10000000),
       title: catName,
       category: "Full Body", // fallback
       type: "Compound",
       muscleFocus: [],
       image: "https://images.unsplash.com/photo-1541534741688-6078c6bfb5c5?auto=format&fit=crop&q=80&w=200&h=200",
       equipment: trueEq,
       notes: "",
       sets: []
    });
  }
}

// Remove duplicates
const uniqueMap = {};
for (const ex of exercises) {
   if (!uniqueMap[ex.title]) {
       uniqueMap[ex.title] = ex;
   }
}
const finalExercises = Object.values(uniqueMap);

export const parsedCsvExercises = finalExercises;
